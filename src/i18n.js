export function translate(locale, key) {
  const language = messages[locale] || messages.ru;
  const value = key.split('.').reduce((current, part) => current?.[part], language);
  return value ?? key.split('.').reduce((current, part) => current?.[part], messages.ru) ?? key;
}

export function sectionLabel(locale, id, fallback) {
  return translate(locale, `shell.nav.${id}`) === `shell.nav.${id}`
    ? fallback
    : translate(locale, `shell.nav.${id}`);
}

export function sectionSubtitle(locale, id, fallback = '') {
  const value = translate(locale, `shell.subtitle.${id}`);
  return value === `shell.subtitle.${id}` ? fallback : value;
}
